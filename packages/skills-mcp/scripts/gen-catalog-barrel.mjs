/**
 * Generates `src/providers/catalog/index.ts` from the provider catalog files.
 *
 *   node packages/skills-mcp/scripts/gen-catalog-barrel.mjs            # write
 *   node packages/skills-mcp/scripts/gen-catalog-barrel.mjs --check    # prove the committed file
 *
 * One import per provider, in file-name order, so adding or removing a
 * `catalog/<provider>.json` file is the only thing that changes this file.
 * `--check` compares instead of writing and exits 1 with a `re-run:` line.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Resolved from this file rather than the working directory: this is run from CI,
// from the package and from the repository root.
const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "..", "src", "providers", "catalog", "index.ts");
const dir = join(here, "..", "src", "providers", "catalog");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort();

const identifiers = new Set();
const providers = files.map((f) => {
  const provider = f.replace(/\.json$/, "");
  if (!/^[a-z0-9-]+$/.test(provider)) {
    throw new Error(`${f} is not a provider toolkitId file name`);
  }
  const parsed = JSON.parse(readFileSync(join(dir, f), "utf8"));
  if (parsed.provider !== provider) {
    throw new Error(`${f} declares provider "${parsed.provider}"; expected "${provider}"`);
  }
  for (const tool of parsed.tools) {
    if (tool.toolkitId !== provider) {
      throw new Error(`${f} contains a ${tool.toolkitId} tool: ${tool.toolSlug}`);
    }
  }
  const identifier = `${provider.replace(/[^a-zA-Z0-9]/g, "_")}Json`;
  if (identifiers.has(identifier)) {
    throw new Error(`duplicate import identifier for ${provider}: ${identifier}`);
  }
  identifiers.add(identifier);
  return { provider, identifier };
});

const imports = providers
  .map((p) => `import ${p.identifier} from "./${p.provider}.json" with { type: "json" };`)
  .join("\n");
const entries = providers.map((p) => `  ${p.identifier},`).join("\n");

const body = `/**
 * Auto-generated by scripts/gen-catalog-barrel.mjs - do not edit by hand.
 *
 * One provider per file: \`catalog/<toolkitId>.json\` is the single unit of
 * change when a provider grows. Run \`node packages/skills-mcp/scripts/gen-catalog-barrel.mjs\`
 * after adding or removing a file.
 */
${imports}

import type { ProviderCatalogFile } from "../types.js";

export const CATALOG_FILES = [
${entries}
] as unknown as ProviderCatalogFile[];
`;

if (process.argv.includes("--check")) {
  let current = null;
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    current = null;
  }
  if (current !== body) {
    console.error(`${outFile} is out of date`);
    console.error("re-run: node packages/skills-mcp/scripts/gen-catalog-barrel.mjs");
    process.exit(1);
  }
  console.log(`the ${providers.length} provider imports are up to date`);
  process.exit(0);
}

writeFileSync(outFile, body);
console.log("wrote", providers.length, "provider imports");
