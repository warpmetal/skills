/**
 * Generates the Cloudflare coverage record from the API spec and the reviewed
 * allowlist:
 *
 *   docs/cloudflare-api-inventory.md   every operation, grouped, with the
 *                                      filter that dropped it or the tool that
 *                                      shipped for it
 *   docs/cloudflare-token-scopes.md    which token permission each shipped tool
 *                                      needs, taken from x-api-token-group and
 *                                      x-cfPermissionsRequired
 *
 * Both files are generated, and `--check` fails when they are out of date, so
 * the docs cannot drift from the allowlist the generators obey.
 *
 *   node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs            [ruta/openapi.json]
 *   node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs --check
 *   node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs --groups
 *   node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs --list /zones
 *   node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs --tool cloudflare_zones_list
 *
 * `openapi.json` is scratch (27 MB, not committed), so the spec path is an
 * argument and the generated docs are what gets reviewed. `--list` is the
 * curation aid: it prints the operations under a path prefix with the name each
 * one would get, so a wave can be chosen without reading the spec by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { AUTH_NONE, loadAllowlist } from "./cloudflare/allowlist.mjs";
import { groupOf, loadCloudflareSpec } from "./cloudflare/spec.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const allowlistPath = join(here, "cloudflare/allowlist.json");
const inventoryPath = join(root, "docs/cloudflare-api-inventory.md");
const scopesPath = join(root, "docs/cloudflare-token-scopes.md");

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const value = (name) => {
  const index = argv.indexOf(name);
  return index >= 0 ? argv[index + 1] : undefined;
};

const specPath = argv.find((entry) => !entry.startsWith("--") && entry.endsWith(".json"))
  ?? join(root, "openapi.json");

const spec = loadCloudflareSpec(specPath);
const allowlist = loadAllowlist(allowlistPath, spec);

if (allowlist.problems.length > 0) {
  console.error(`${allowlist.problems.length} problem(s) in ${allowlistPath}:`);
  for (const problem of allowlist.problems) console.error(`  ${problem}`);
  process.exit(1);
}

const includedByKey = new Map(
  allowlist.entries.map((entry) => [`${entry.method} ${entry.path}`, entry]),
);
const includeCount = allowlist.entries.length;

/** Groups keyed by `scope/module`, in a stable order a reviewer can diff. */
function groupOperations() {
  const groups = new Map();
  for (const op of spec.ops) {
    const key = groupOf(op);
    const bucket = groups.get(key) ?? { key, ops: [] };
    bucket.ops.push(op);
    groups.set(key, bucket);
  }
  return [...groups.values()].sort((a, b) => a.key.localeCompare(b.key));
}

function opsLine(op) {
  return `\`${op.method}\` \`${op.path}\``;
}

function waveTable() {
  const rows = [];
  for (const [wave, meta] of Object.entries(allowlist.document.waves ?? {})) {
    const entries = allowlist.entries.filter((entry) => entry.wave === wave);
    const groups = [...new Set(entries.map((entry) => groupOf(entry.op)))];
    rows.push(
      `| \`${wave}\` | ${meta.status} | ${entries.length} | ${meta.scope ?? ""} | ${
        groups.length > 0 ? groups.map((group) => `\`${group}\``).join(", ") : "-"
      } |`,
    );
  }
  return rows.join("\n");
}

function renderInventory() {
  const counts = spec.counts;
  const groups = groupOperations();
  const lines = [
    "# Cloudflare API inventory",
    "",
    "<!-- Generated by `packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs`; do not edit by hand. -->",
    "",
    `Source: **${spec.info.title} ${spec.info.version}**, served at \`${spec.servers[0]?.url ?? ""}\`.`,
    `Spec digest: \`sha256:${spec.sha256}\`.`,
    "",
    "`openapi.json` is not committed (27 MB of scratch), so this file - not the",
    "spec - is what a reviewer reads. `--check` fails when it is out of date,",
    "which is what keeps it true.",
    "",
    "## What the filter drops",
    "",
    "| Bucket | Operations | Rule |",
    "| --- | --- | --- |",
    `| Everything documented | ${counts.operations} | every operation in the spec, across ${counts.paths} paths |`,
    `| \`x-forge-hidden\` | ${counts.hidden} | hidden from Cloudflare's own Forge docs: internal or unreleased |`,
    `| \`x-fern-ignore\` | ${counts.fernIgnore} | dropped from the published Fern docs before Forge replaced them |`,
    `| Reviewable | ${counts.reviewable} | what remains, and the pool every wave is chosen from |`,
    `| Shipped | ${includeCount} | pinned in \`scripts/cloudflare/allowlist.json\` |`,
    "",
    `${counts.confirm} reviewable operations carry \`x-forge-require-confirmation\`,`,
    `${counts.cfDeprecation} carry \`x-cfDeprecation\` and ${counts.publicHint} declare \`security: []\`.`,
    `${counts.unsupportedBody} operations take a body with no field list to expose`,
    `(multipart, binary or a bare string) and ${counts.freeFormBody} take a body whose`,
    "fields the spec does not publish; either is shipped only where the allowlist says so.",
    "",
    "## Waves",
    "",
    "| Wave | Status | Tools | Scope | Groups |",
    "| --- | --- | --- | --- | --- |",
    waveTable(),
    "",
    "## Shipped tools",
    "",
    "| # | Tool | Method | Path | Wave | Flags |",
    "| --- | --- | --- | --- | --- | --- |",
    includedTable(),
    "",
  ];

  if (allowlist.warnings.length > 0) {
    lines.push("## Review notes", "");
    for (const warning of allowlist.warnings) lines.push(`- ${warning}`);
    lines.push("");
  }

  const document = allowlist.document;
  if (document.retiredNote || document.renamed || document.retired) {
    lines.push("## Renames and retirements", "");
    if (document.retiredNote) lines.push(document.retiredNote, "");
    for (const [from, to] of Object.entries(document.renamed ?? {})) {
      lines.push(`- \`${from}\` -> \`${to}\``);
    }
    for (const slug of document.retired ?? []) {
      lines.push(`- \`${slug}\` no longer exists`);
    }
    for (const [slug, note] of Object.entries(document.reused ?? {})) {
      lines.push(`- \`${slug}\` is reused: ${note}`);
    }
    lines.push("");
  }

  lines.push(
    "## Every reviewable operation, by group",
    "",
    "Groups are `scope/module`: the first path segment, then the first word of the",
    "module. An operation that is not listed as shipped is not absent by accident:",
    "the wave plan above says when it is due, and the allowlist is where that",
    "happens.",
    "",
  );

  for (const group of groups) {
    const reviewable = group.ops.filter((op) => !op.filtered);
    const filtered = group.ops.length - reviewable.length;
    const shipped = group.ops.filter((op) => includedByKey.has(`${op.method} ${op.path}`));
    lines.push(
      `### \`${group.key}\` - ${shipped.length} of ${reviewable.length} reviewable shipped${
        filtered > 0 ? `, ${filtered} filtered out` : ""
      }`,
      "",
    );
    for (const op of shipped) {
      const entry = includedByKey.get(`${op.method} ${op.path}`);
      lines.push(`- \`${entry.toolSlug}\` - ${opsLine(op)}`);
    }
    const pending = reviewable.filter((op) => !includedByKey.has(`${op.method} ${op.path}`));
    if (pending.length > 0) {
      lines.push("", `Not shipped (${pending.length}):`);
      for (const op of pending) lines.push(`- ${opsLine(op)}`);
    }
    lines.push("");
  }

  lines.push(
    "## Regenerating",
    "",
    "```sh",
    "node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs   # writes this file",
    "node packages/warpmetal-cli/scripts/gen-cloudflare-routes.mjs      # writes the route table",
    "node packages/skills-mcp/scripts/gen-cloudflare-catalog.mjs        # writes the catalog",
    "```",
    "",
  );

  return `${lines.join("\n")}\n`;
}

function renderScopes() {
  // An operation that accepts any of many permissions (`GET /zones/{zone_id}`
  // lists every read permission the API knows) would otherwise be printed under
  // 40 groups, which reads as "this token needs all 40". Above this many groups
  // the operation is listed separately as an any-of, and the per-group sections
  // keep the operations whose group list is the permission they actually need.
  const ANY_OF_THRESHOLD = 3;
  const byGroup = new Map();
  const anyOf = [];
  const missing = [];
  const withIds = [];
  for (const entry of allowlist.entries) {
    if (entry.op.permissions.length > 0) {
      withIds.push(entry);
    }
    if (entry.op.tokenGroups.length === 0 && entry.op.permissions.length === 0) {
      if (entry.auth !== AUTH_NONE) missing.push(entry);
      continue;
    }
    if (entry.op.tokenGroups.length > ANY_OF_THRESHOLD) {
      anyOf.push(entry);
      continue;
    }
    for (const name of entry.op.tokenGroups) {
      const bucket = byGroup.get(name) ?? { name, entries: [] };
      bucket.entries.push(entry);
      byGroup.set(name, bucket);
    }
  }

  const lines = [
    "# Cloudflare token scopes",
    "",
    "<!-- Generated by `packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs`; do not edit by hand. -->",
    "",
    "Which API-token permission each shipped tool needs, read from the spec's",
    "`x-api-token-group` (the permission group name the dashboard shows). A token",
    "needs the union of the groups for the tools it calls, within the resource",
    "scope: a zone permission applies to one zone, an account permission to one",
    "account, and the `/user/tokens` tools need a user-scoped token.",
    "",
    "An operation that accepts *any* of many permissions is listed under \"Accepts",
    "any of\" rather than once per group, so a group section means what it says.",
    "",
    "```sh",
    "warpmetal env store set cloudflare.token --stdin   # reads the token from stdin",
    "```",
    "",
  ];

  for (const bucket of [...byGroup.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`## ${bucket.name}`, "", `Tools (${bucket.entries.length}):`);
    for (const entry of bucket.entries) {
      lines.push(`- \`${entry.toolSlug}\` - \`${entry.op.method}\` \`${entry.op.path}\``);
    }
    lines.push("");
  }

  if (anyOf.length > 0) {
    lines.push(
      "## Accepts any of many permissions",
      "",
      "Cloudflare documents these as usable with any one of a long list of",
      "permissions; the count is how many it accepts.",
      "",
    );
    for (const entry of anyOf) {
      lines.push(
        `- \`${entry.toolSlug}\` - \`${entry.op.method}\` \`${entry.op.path}\` - any of ${entry.op.tokenGroups.length}`,
      );
    }
    lines.push("");
  }

  if (withIds.length > 0) {
    lines.push(
      "## Cloudflare's internal permission ids",
      "",
      "`x-cfPermissionsRequired` as the API reports it, per tool. These are not the",
      "dashboard names above; they are what a policy document or an error message",
      "quotes back.",
      "",
    );
    for (const entry of withIds) {
      lines.push(`- \`${entry.toolSlug}\`: ${entry.op.permissions.map((id) => `\`${id}\``).join(", ")}`);
    }
    lines.push("");
  }

  if (missing.length > 0) {
    lines.push(
      "## Tools with no permission metadata",
      "",
      "The spec publishes no token permission for these, so they cannot be filed",
      "under a group above. Their allowlist entry carries the reviewed note:",
      "",
    );
    for (const entry of missing) {
      lines.push(`- \`${entry.toolSlug}\` - ${entry.op.method} ${entry.op.path}`);
    }
    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}

/** A prefix that stops at a path-segment boundary: `/list /zones` is not /zones/{id}/dns_records. */
function matchesPrefix(path, prefix) {
  if (prefix === "/") return true;
  const base = prefix.endsWith("/") ? prefix.slice(0, -1) : prefix;
  return path === base || path.startsWith(`${base}/`);
}

function listOperations(prefix) {
  const rows = spec.ops
    .filter((op) => matchesPrefix(op.path, prefix))
    .sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
  for (const op of rows) {
    const flags = [
      op.filtered ? "FILTERED" : "reviewable",
      op.confirm ? "confirm" : "",
      op.deprecated ? "deprecated" : "",
      op.stability && op.stability !== "stable" ? op.stability : "",
    ].filter(Boolean);
    console.log(
      `${op.method.padEnd(6)} ${op.path.padEnd(58)} ${String(op.toolSlug).padEnd(46)} ` +
        `body=${op.body?.kind ?? "none"} fields=${op.body?.fields.length ?? 0} ` +
        `q=${op.queryParams.length} [${flags.join(" ")}] ${op.tokenGroups.join(" + ")}`,
    );
  }
  console.log(`${rows.length} operation(s) under ${prefix}`);
}

function suggest(prefix, wave) {
  const rows = spec.ops
    .filter((op) => matchesPrefix(op.path, prefix))
    .sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
  const entries = rows.map((op) => ({
    toolSlug: op.toolSlug,
    method: op.method,
    path: op.path,
    wave,
    reason: op.summary ? `${op.summary}.` : "TODO",
    destructive: op.method === "DELETE",
    auth: "api-token",
    ...(op.filtered ? { keepFiltered: true, filterNote: "TODO: why this hidden operation ships" } : {}),
    ...(op.body?.kind === "free-form" ? { freeFormBody: true } : {}),
    ...(op.body?.kind === "unsupported" ? { unsupportedBody: op.body.contentType } : {}),
  }));
  console.log(JSON.stringify(entries, null, 2));
}

function describeTool(slug) {
  const entry = allowlist.bySlug.get(slug);
  if (!entry) {
    console.error(`${slug} is not in the allowlist`);
    process.exit(1);
  }
  const op = entry.op;
  console.log(JSON.stringify({
    toolSlug: entry.toolSlug,
    derived: op.toolSlug,
    wave: entry.wave,
    method: op.method,
    path: op.path,
    summary: op.summary,
    flags: {
      readOnly: op.method === "GET",
      destructive: entry.destructive,
      confirm: op.confirm,
      deprecated: op.deprecated,
      stability: op.stability,
      filtered: op.filtered,
      keepFiltered: entry.keepFiltered === true,
      body: op.body?.kind ?? "none",
      freeFormBody: entry.freeFormBody === true,
      auth: entry.auth,
    },
    pathParams: op.pathParams.map((p) => ({ wire: p.name, arg: p.snake, required: p.required })),
    queryParams: op.queryParams.map((p) => ({
      wire: p.name,
      arg: p.snake,
      required: p.required,
      collection: p.collection,
      type: p.schema.type ?? null,
      enum: p.schema.enum ?? null,
    })),
    bodyFields: (op.body?.fields ?? []).map((f) => ({
      wire: f.name,
      arg: f.snake,
      required: f.required,
      type: f.schema.type ?? null,
    })),
    tokenGroups: op.tokenGroups,
    permissions: op.permissions,
  }, null, 2));
}

function includedTable() {
  const rows = allowlist.entries.map((entry, index) => {
    const op = entry.op;
    const flags = [
      entry.override ? "renamed" : "",
      entry.keepFiltered ? "spec-hidden" : "",
      entry.freeFormBody ? "free-form body" : "",
      entry.rawBody ? "raw body" : "",
      entry.auth === AUTH_NONE ? "no auth" : "",
      entry.destructive ? "destructive" : "",
      op.confirm ? "needs confirmation" : "",
      op.deprecated ? "deprecated" : "",
      op.stability && op.stability !== "stable" ? op.stability : "",
    ].filter(Boolean);
    return `| ${index + 1} | \`${entry.toolSlug}\` | \`${op.method}\` | \`${op.path}\` | ${entry.wave} | ${
      flags.length > 0 ? flags.join(", ") : "-"
    } |`;
  });
  return rows.join("\n");
}

function groupCounts() {
  const groups = groupOperations();
  for (const group of groups) {
    const reviewable = group.ops.filter((op) => !op.filtered).length;
    const shipped = group.ops.filter((op) => includedByKey.has(`${op.method} ${op.path}`)).length;
    console.log(
      `${String(shipped).padStart(4)} / ${String(reviewable).padStart(4)} reviewable  ` +
        `${String(group.ops.length - reviewable).padStart(4)} filtered  ${group.key}`,
    );
  }
  console.log(`${groups.length} group(s) in ${specPath}`);
}

if (flag("--groups")) {
  groupCounts();
  process.exit(0);
}
if (flag("--list")) {
  listOperations(value("--list") ?? "/");
  process.exit(0);
}
if (flag("--suggest")) {
  suggest(value("--suggest") ?? "/", value("--wave") ?? "w1");
  process.exit(0);
}
if (flag("--tool")) {
  describeTool(value("--tool") ?? "");
  process.exit(0);
}

const inventory = renderInventory();
const scopes = renderScopes();

if (flag("--check")) {
  const stale = [];
  for (const [path, expected] of [
    [inventoryPath, inventory],
    [scopesPath, scopes],
  ]) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = null;
    }
    if (current !== expected) stale.push(path);
  }
  if (stale.length > 0) {
    console.error(`out of date: ${stale.join(", ")}`);
    console.error("re-run: node packages/warpmetal-cli/scripts/gen-cloudflare-inventory.mjs");
    process.exit(1);
  }
  console.log("cloudflare inventory and scope docs are up to date");
  process.exit(0);
}

writeFileSync(inventoryPath, inventory);
writeFileSync(scopesPath, scopes);
console.log(`wrote ${inventoryPath}`);
console.log(`wrote ${scopesPath}`);
console.log(
  `${includeCount} tool(s) in the allowlist; ${spec.counts.reviewable} reviewable operations in the spec`,
);
if (allowlist.warnings.length > 0) {
  console.log(`${allowlist.warnings.length} review note(s):`);
  for (const warning of allowlist.warnings) console.log(`  ${warning}`);
}
