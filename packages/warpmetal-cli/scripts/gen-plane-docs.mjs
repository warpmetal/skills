/**
 * Generates the two Plane documents: `docs/plane-mcp-inventory.md`, what the pin
 * says, and `docs/plane-endpoint-map.md`, what we ship.
 *
 * Plane publishes no OpenAPI document, so the file a reviewer reads cannot be the
 * spec - there is none. It has to be the two things this repository *did* review:
 * the pinned inventory of the vendor's own surface (with the rules by which
 * actions were left out), and the tool-by-tool endpoint map (with the vendor call
 * site each endpoint was read from). Both are written from the files the
 * generators obey, so the documents cannot claim anything the surface does not do.
 *
 *   node packages/warpmetal-cli/scripts/gen-plane-docs.mjs
 *   node packages/warpmetal-cli/scripts/gen-plane-docs.mjs --check
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { argumentRoles, loadAllowlist } from "./plane/allowlist.mjs";
import { API_ORIGIN, ENDPOINTS } from "./plane/endpoints.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const inventory = JSON.parse(readFileSync(join(here, "plane/inventory.json"), "utf8"));
const allowlist = loadAllowlist(join(here, "plane/allowlist.json"), inventory, ENDPOINTS);

if (allowlist.problems.length > 0) {
  console.error(`${allowlist.problems.length} problem(s) in the Plane allowlist:`);
  for (const problem of allowlist.problems) console.error(`  ${problem}`);
  process.exit(1);
}

const waveOf = (wave) => allowlist.entries.filter((entry) => entry.wave === wave);
const rules = new Map();
for (const entry of allowlist.excluded) {
  const list = rules.get(entry.rule) ?? [];
  list.push(entry);
  rules.set(entry.rule, list);
}
const RULE_PROSE = {
  "more-than-one-request":
    "The vendor's action is more than one HTTP request - a listing that also reads each page's detail, an archive that retrieves, patches and archives. One of our tools is one request, so these are out rather than flattened into something the vendor never promised.",
  "shared-dispatch-branch":
    "The vendor's dispatcher answers for this action inside a branch it shares with others, so its call site cannot be attributed to the action alone. Shipping it would ship an endpoint we cannot tie to the action we named.",
  "no-request":
    "The vendor's action issues no request at all: the tool answers from text it carries. A reference table is not an API call, so it is not a tool of ours.",
  "multipart-body":
    "The request carries file bytes, and the vendor reaches it with a multipart upload followed by a patch. A JSON tool argument cannot carry bytes and this surface has no encoding for them.",
};

const endpointMethod = (entry) =>
  typeof entry.endpoint.method === "string"
    ? entry.endpoint.method
    : Object.values(entry.endpoint.method.cases).map((variant) => variant.method).join(" / ");

const endpointPath = (entry) =>
  typeof entry.endpoint.path === "string"
    ? entry.endpoint.path
    : Object.entries(entry.endpoint.path.cases)
        .map(([value, path]) => `${path} (${entry.endpoint.path.arg} = ${value})`)
        .join(" or ");

const inventoryDoc = [
  "# Plane MCP inventory",
  "",
  "<!-- Generated by `packages/warpmetal-cli/scripts/gen-plane-docs.mjs`; do not edit by hand. -->",
  "",
  `Pinned source: **${inventory.source.repository} ${inventory.source.tag}** (${inventory.source.license}), published ${inventory.source.publishedAt ?? "unknown"}.`,
  "",
  "Plane publishes no OpenAPI document - the schema endpoint answers 404 and the",
  "documentation host serves its own copy - so the pin for this provider is the",
  "vendor's MCP server itself: one module per resource whose `ACTIONS` tuple is, by",
  "that package's own design, the contract behind its tool descriptions, MCP",
  "annotations and argument validation. `scripts/plane/fetch-inventory.mjs` reads",
  "that source at the pinned tag, records a sha256 for every file, and derives",
  "`inventory.json` from it; `npm run check:plane-inventory` fails when either the",
  "tag or the committed inventory moves.",
  "",
  "## What the pin says",
  "",
  "| Measure | Count |",
  "| --- | --- |",
  `| Tools | ${inventory.counts.tools} |`,
  `| Actions | ${inventory.counts.actions} |`,
  `| Read actions | ${inventory.counts.read} |`,
  `| Actions the vendor marks destructive | ${inventory.counts.destructive} |`,
  `| Actions that are a single request | ${inventory.counts.shapes.single} |`,
  `| Actions that are more than one request | ${inventory.counts.shapes.multi} |`,
  `| Actions that issue no request | ${inventory.counts.shapes.none} |`,
  `| Retired action aliases | ${inventory.counts.legacy} |`,
  "",
  "Every action also carries the line it was declared on and the client member it",
  "calls (`sdkCalls`), which is the evidence each endpoint in",
  "`docs/plane-endpoint-map.md` is reviewed against.",
  "",
  "## What we ship",
  "",
  `**${allowlist.entries.length} tools** from ${inventory.counts.actions} actions:`,
  "",
  "| Wave | Tools | What it is |",
  "| --- | --- | --- |",
  ...["p1", "p2"].map((wave) => `| \`${wave}\` | ${waveOf(wave).length} | ${allowlist.document.waves?.[wave]?.note ?? ""} |`),
  "",
  `**${allowlist.excluded.length} actions** are deliberately excluded, and ${allowlist.document.pending?.length ?? 0} are pending review.`,
  "",
  "## Why an action is excluded",
  "",
];

/** The excluded actions, grouped by the rule that excludes them. */
for (const [rule, entries] of [...rules].sort((left, right) => right[1].length - left[1].length)) {
  inventoryDoc.push(`### ${rule} (${entries.length})`, "", RULE_PROSE[rule] ?? "", "");
  for (const entry of entries) inventoryDoc.push(`- \`${entry.id}\` - ${entry.why}`);
  inventoryDoc.push("");
}

const pending = allowlist.document.pending ?? [];
inventoryDoc.push(
  "## Pending review",
  "",
  pending.length === 0
    ? "Every action the pin declares is either shipped or excluded."
    : "These actions are in the pin and have not been reviewed for our surface yet. The " +
        "validator refuses a pin that adds an action no list mentions, so this cannot silently grow.",
  "",
);
for (const id of pending) inventoryDoc.push(`- \`${id}\``);
inventoryDoc.push("");

const mapDoc = [
  "# Plane endpoint map",
  "",
  "<!-- Generated by `packages/warpmetal-cli/scripts/gen-plane-docs.mjs`; do not edit by hand. -->",
  "",
  `Every tool in the Plane surface, the request it builds, and the vendor call site the`,
  `request was read from. Origin: \`${API_ORIGIN}\`, prefix \`/api/v1\`, credential in the`,
  "`x-api-key` header, workspace slug from the `plane.workspace_slug` secret.",
  "",
  "`sdk` is the member `fetch-inventory.mjs` recorded for that action: the same string",
  "the pinned release calls, and the validator refuses an entry whose endpoint names",
  "any other call site. `arguments` says where each of the action's arguments goes.",
  "",
  "| Tool | Request | Path | sdk | Arguments | Notes |",
  "| --- | --- | --- | --- | --- | --- |",
];

for (const entry of allowlist.entries) {
  const roles = argumentRoles(entry);
  const route = roles.placeholders.has("workspace") ? "workspace path" : "no workspace";
  const argumentNote = [
    roles.placeholders.size > 0 ? `path: ${[...roles.placeholders].filter((name) => name !== "workspace").join(", ") || "-"}` : "",
    roles.queries.length > 0 ? `query: ${roles.queries.join(", ")}` : "",
    roles.bodyArgs.length > 0 ? `body: ${roles.bodyArgs.join(", ")}` : "",
    roles.chosenBy !== undefined ? `chooses: ${roles.chosenBy}` : "",
    (entry.endpoint.requireArgs ?? []).length > 0 ? `requires: ${entry.endpoint.requireArgs.join(", ")}` : "",
  ]
    .filter(Boolean)
    .join("; ");
  const notes = [entry.endpoint.note, entry.flowNote, entry.destructiveReason].filter(Boolean).join(" ");
  mapDoc.push(
    `| \`${entry.toolSlug}\` | ${endpointMethod(entry)} | \`${endpointPath(entry)}\` | \`${entry.endpoint.sdk}\` | ` +
      `${argumentNote} (${route}) | ${notes.replace(/\|/g, "\\|")} |`,
  );
}
mapDoc.push("");

const outputs = [
  { file: join(root, "docs/plane-mcp-inventory.md"), text: `${inventoryDoc.join("\n")}` },
  { file: join(root, "docs/plane-endpoint-map.md"), text: `${mapDoc.join("\n")}` },
];

if (process.argv.includes("--check")) {
  let stale = 0;
  for (const output of outputs) {
    let current = null;
    try {
      current = readFileSync(output.file, "utf8");
    } catch {
      current = null;
    }
    if (current !== output.text) {
      stale += 1;
      console.error(`${output.file} is out of date`);
    }
  }
  if (stale > 0) {
    console.error("re-run: node packages/warpmetal-cli/scripts/gen-plane-docs.mjs");
    process.exit(1);
  }
  console.log("the plane docs are up to date");
  process.exit(0);
}

for (const output of outputs) writeFileSync(output.file, output.text);
console.log(
  `wrote docs/plane-mcp-inventory.md (${allowlist.excluded.length} excluded, ${pending.length} pending) and ` +
    `docs/plane-endpoint-map.md (${allowlist.entries.length} tools)`,
);
